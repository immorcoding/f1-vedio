// Builds the Yas Marina 2021 centre line (src/tracks/yas-marina-2021.line.ts) from OpenStreetMap.
// Input: references/yas-marina/osm-raceway.json (git-ignored; see docs/assets/reference-register.md), an Overpass
// export of the circuit's raceway ways: `way["highway"="raceway"](24.455,54.585,24.485,54.615); out body geom;`.
// © OpenStreetMap contributors, ODbL.
//
// The GP loop is the chain of ways below (checked: each one starts on the node the previous one ends on). The
// points are projected to metres (x east, y south, so SVG's y-down is north-up), smoothed lightly (OSM corners are
// polylines), resampled every STEP metres and rotated so the lap starts on the finish line.
// Run: node scripts/trace-track-yas.mjs
import fs from "node:fs";

const SRC = "references/yas-marina/osm-raceway.json";
const OUT = "src/tracks/yas-marina-2021.line.ts";
const LOOP = [168477013, 1469184731, 1469184732, 188337196, 1255169703, 1255169704];
const STEP = 4;
// Finish line: on the main straight, 33 % of the way from its west end (after the last corner) to its east end
// (before turn 1), where the CC0 2021 layout map puts the chequered flag.
const FINISH_SHARE = 0.33;

const osm = JSON.parse(fs.readFileSync(SRC, "utf8"));
const ways = new Map(osm.elements.map((e) => [e.id, e]));

let pts = [];
let lastNode = null;
for (const id of LOOP) {
  const w = ways.get(id);
  if (!w) throw new Error(`way ${id} missing`);
  if (lastNode !== null && w.nodes[0] !== lastNode)
    throw new Error(`way ${id} does not start where the previous ended`);
  const geom = lastNode === null ? w.geometry : w.geometry.slice(1);
  pts.push(...geom);
  lastNode = w.nodes.at(-1);
}
if (lastNode !== ways.get(LOOP[0]).nodes[0]) throw new Error("loop not closed");
pts.pop(); // the closing node repeats the first

const lat0 = pts.reduce((s, p) => s + p.lat, 0) / pts.length;
const lon0 = pts.reduce((s, p) => s + p.lon, 0) / pts.length;
const mLon = 111320 * Math.cos((lat0 * Math.PI) / 180);
const mLat = 110574;
let xy = pts.map((p) => [(p.lon - lon0) * mLon, -(p.lat - lat0) * mLat]);

// Chaikin smoothing, two passes, on the closed loop.
for (let pass = 0; pass < 2; pass++) {
  const out = [];
  for (let i = 0; i < xy.length; i++) {
    const a = xy[i];
    const b = xy[(i + 1) % xy.length];
    out.push([0.75 * a[0] + 0.25 * b[0], 0.75 * a[1] + 0.25 * b[1]]);
    out.push([0.25 * a[0] + 0.75 * b[0], 0.25 * a[1] + 0.75 * b[1]]);
  }
  xy = out;
}

// Resample at STEP metres.
const resample = (line) => {
  const seg = line.map((p, i) => {
    const q = line[(i + 1) % line.length];
    return Math.hypot(q[0] - p[0], q[1] - p[1]);
  });
  const total = seg.reduce((s, d) => s + d, 0);
  const n = Math.round(total / STEP);
  const out = [];
  let i = 0;
  let acc = 0;
  for (let k = 0; k < n; k++) {
    const s = (k * total) / n;
    while (acc + seg[i] < s) acc += seg[i++];
    const t = (s - acc) / seg[i];
    const p = line[i];
    const q = line[(i + 1) % line.length];
    out.push([p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t]);
  }
  return { out, total };
};
let { out: line, total } = resample(xy);

// Main straight: the longest run whose heading stays within 4° of its mean, among runs heading roughly east.
const heading = (i) => {
  const p = line[i];
  const q = line[(i + 1) % line.length];
  return Math.atan2(q[1] - p[1], q[0] - p[0]);
};
let best = { len: 0, from: 0 };
for (let i = 0; i < line.length; i++) {
  const h0 = heading(i);
  if (Math.abs(h0) > 0.5) continue; // not eastbound
  let j = i;
  while (j - i < line.length && Math.abs(heading(j % line.length) - h0) < 0.07) j++;
  if (j - i > best.len) best = { len: j - i, from: i };
}
const finish = (best.from + Math.round(best.len * FINISH_SHARE)) % line.length;
line = [...line.slice(finish), ...line.slice(0, finish)];

const r1 = (v) => Math.round(v * 10) / 10;
const body = line.map(([x, y]) => `${r1(x)},${r1(y)}`).join(" ");
fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/trace-track-yas.mjs from OpenStreetMap (© OpenStreetMap contributors, ODbL) — do not edit.
// Yas Marina Circuit, 2021 F1 layout: centre line in metres (x east, y south), one point every ${STEP} m, starting
// on the finish line and running in race direction. Lap length of the line: ${total.toFixed(0)} m (official: 5281 m).
export const YAS_2021_LINE = "${body}";
`,
);
console.log(
  `points ${line.length}, lap ${total.toFixed(1)} m, main straight ${best.len * STEP} m, finish at index ${finish}`,
);
