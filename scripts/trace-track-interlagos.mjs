// Builds the Interlagos centre line (src/tracks/interlagos-2008.line.ts) from OpenStreetMap.
// Input: references/interlagos/osm-raceway.json (git-ignored; see docs/assets/reference-register.md), an Overpass
// export of the circuit's raceway ways: `way["highway"="raceway"](-23.71,-46.705,-23.695,-46.69); out body geom;`.
// © OpenStreetMap contributors, ODbL.
//
// The GP loop is the chain of named ways below, in race direction (anticlockwise), checked node to node. The layout
// has not changed since 2008 (4.309 km both then and now). Same recipe as trace-track-yas.mjs: project to metres
// (x east, y south), light Chaikin smoothing, resample every STEP metres, start the lap on the finish line.
// It also prints the lap distance where each named way starts, for the `corners` table in interlagos-2008.ts.
// Run: node scripts/trace-track-interlagos.mjs
import fs from "node:fs";

const SRC = "references/interlagos/osm-raceway.json";
const OUT = "src/tracks/interlagos-2008.line.ts";
// Ways from the pit-straight section after the pit entry, round the lap, back to the pit straight.
const LOOP = [
  190164733, // Arquibancadas (pit straight)
  138567241,
  131439569, // S do Senna
  189535473,
  807691487,
  138566995, // Curva do Sol
  138567001, // Reta Oposta
  138566996, // Descida do Lago
  807691486,
  138567000,
  138566997, // Ferradura
  138566994, // Curva do Laranjinha
  138567002,
  190164735, // Esse
  138566998, // Pinheirinho
  138566993, // Bico de Pato
  190164734, // Mergulho
  138566999,
  138567236, // Junção
  189535472,
  190164736,
  138567242, // Café
  190164737,
  138567239, // Subida dos Boxes
  138567234,
];
const STEP = 4;
// Finish line: on the pit straight, this share of the way along the Arquibancadas way (from the pit entry end).
const FINISH_SHARE = 0.55;

const osm = JSON.parse(fs.readFileSync(SRC, "utf8"));
const ways = new Map(osm.elements.map((e) => [e.id, e]));

let pts = [];
const wayStart = [];
let lastNode = null;
for (const id of LOOP) {
  const w = ways.get(id);
  if (!w) throw new Error(`way ${id} missing`);
  if (lastNode !== null && w.nodes[0] !== lastNode)
    throw new Error(`way ${id} does not start where the previous ended`);
  wayStart.push({ id, name: w.tags?.name ?? "", at: pts.length });
  const geom = lastNode === null ? w.geometry : w.geometry.slice(1);
  pts.push(...geom);
  lastNode = w.nodes.at(-1);
}
if (lastNode !== ways.get(LOOP[0]).nodes[0]) throw new Error("loop not closed");
pts.pop();

const lat0 = pts.reduce((s, p) => s + p.lat, 0) / pts.length;
const lon0 = pts.reduce((s, p) => s + p.lon, 0) / pts.length;
const mLon = 111320 * Math.cos((lat0 * Math.PI) / 180);
const mLat = 110574;
const raw = pts.map((p) => [(p.lon - lon0) * mLon, -(p.lat - lat0) * mLat]);

// distance along the raw loop of each raw point
const rawCum = [0];
for (let i = 1; i < raw.length; i++)
  rawCum.push(rawCum[i - 1] + Math.hypot(raw[i][0] - raw[i - 1][0], raw[i][1] - raw[i - 1][1]));
const rawTotal = rawCum.at(-1) + Math.hypot(raw[0][0] - raw.at(-1)[0], raw[0][1] - raw.at(-1)[1]);

let xy = raw;
for (let pass = 0; pass < 2; pass++) {
  const out = [];
  for (let i = 0; i < xy.length; i++) {
    const a = xy[i];
    const b = xy[(i + 1) % xy.length];
    out.push([0.75 * a[0] + 0.25 * b[0], 0.75 * a[1] + 0.25 * b[1]]);
    out.push([0.25 * a[0] + 0.75 * b[0], 0.25 * a[1] + 0.75 * b[1]]);
  }
  xy = out;
}

const seg = xy.map((p, i) => {
  const q = xy[(i + 1) % xy.length];
  return Math.hypot(q[0] - p[0], q[1] - p[1]);
});
const total = seg.reduce((s, d) => s + d, 0);
const n = Math.round(total / STEP);
let line = [];
{
  let i = 0;
  let acc = 0;
  for (let k = 0; k < n; k++) {
    const s = (k * total) / n;
    while (acc + seg[i] < s) acc += seg[i++];
    const t = (s - acc) / seg[i];
    const p = xy[i];
    const q = xy[(i + 1) % xy.length];
    line.push([p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t]);
  }
}

// raw distance → smoothed distance (same share of the lap)
const toLine = (rawS) => (rawS / rawTotal) * total;
const arqEnd = rawCum[wayStart[1].at];
const finishS = toLine(arqEnd * FINISH_SHARE);
const finishIdx = Math.round(finishS / (total / n)) % n;
line = [...line.slice(finishIdx), ...line.slice(0, finishIdx)];
const lapS = (rawS) => {
  const s = toLine(rawS) - finishIdx * (total / n);
  return Math.round(((s % total) + total) % total);
};

const r1 = (v) => Math.round(v * 10) / 10;
const body = line.map(([x, y]) => `${r1(x)},${r1(y)}`).join(" ");
fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/trace-track-interlagos.mjs from OpenStreetMap (© OpenStreetMap contributors, ODbL) — do not edit.
// Autódromo José Carlos Pace (Interlagos): centre line in metres (x east, y south), one point every ${STEP} m, starting
// on the finish line and running in race direction (anticlockwise). Lap length of the line: ${total.toFixed(0)} m (official: 4309 m).
export const INTERLAGOS_LINE = "${body}";
`,
);
console.log(`points ${line.length}, lap ${total.toFixed(1)} m`);
for (const w of wayStart) console.log(`${String(lapS(rawCum[w.at])).padStart(5)} m  ${w.id} ${w.name}`);
